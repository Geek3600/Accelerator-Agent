def build_outputs(args: argparse.Namespace) -> dict[str, Any]:
    run_dir = args.run_dir.resolve()
    params = generated_top_params(run_dir)
    layers = model_layers(run_dir)
    chisel_dir = run_dir / "generated" / "chisel"
    board_dir = run_dir / "generated" / "board_integration"
    paths = {
        "run_multilayer": board_dir / "CaseMultiLayerSystemTop.sv",
        "axi_wrapper": board_dir / "CaseAxiBoardSystemTop.sv",
        "testbench": board_dir / "case_axi_board_tb.sv",
        "manifest": run_dir / "verification" / "board_simulation" / "case_tb_generator_manifest.json",
    }
    ml_text = multilayer_sv(params, layers)
    write_text(paths["run_multilayer"], ml_text)
    write_text(paths["axi_wrapper"], axi_wrapper_sv(params, layers))
    write_text(paths["testbench"], tb_sv(layers))
    manifest = {
        "schema_version": "spatialaccagent.case_tb_generator.v0",
        "run_dir": str(run_dir),
        "num_layers": layers,
        "generated_top_params": params,
        "outputs": {name: str(path) for name, path in paths.items() if name != "manifest"},
        "notes": [
            "CaseLayerPipelineTop chains GeneratedAcceleratorTop instances with ready/valid streams.",
            "CaseAxiBoardSystemTop is an AXI/DDR scaffold for VCS closure; runtime bitstream and board pass still require separate evidence.",
        ],
    }
    write_json(paths["manifest"], manifest)
    return manifest | {"manifest_path": str(paths["manifest"])}


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate case AXI/DDR VCS scaffold")
    parser.add_argument("--run-dir", type=Path, required=True)
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    manifest = build_outputs(args)
    print(manifest["manifest_path"])
    for path in manifest["outputs"].values():
        print(path)
    return 0


