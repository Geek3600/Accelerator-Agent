def write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")


def write_json(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, indent=2, sort_keys=True)
        f.write("\n")


def read_json(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as f:
        data = json.load(f)
    if not isinstance(data, dict):
        raise RuntimeError(f"expected JSON object: {path}")
    return data


def width_from_decl(text: str, port: str, default: int) -> int:
    pattern = rf"\b(?:input|output)\s+(?P<range>\[[^\]]+\])?\s*{re.escape(port)}\b"
    match = re.search(pattern, text)
    if not match:
        return default
    rng = match.group("range")
    if not rng:
        return 1
    values = re.match(r"\[(\d+)\s*:\s*(\d+)\]", rng)
    if not values:
        return default
    hi = int(values.group(1))
    lo = int(values.group(2))
    return abs(hi - lo) + 1


def generated_top_params(run_dir: Path) -> dict[str, int]:
    top = run_dir / "generated" / "chisel" / "GeneratedAcceleratorTop.sv"
    if not top.is_file():
        raise RuntimeError(f"generated accelerator top is missing: {top}")
    text = top.read_text(encoding="utf-8", errors="ignore")
    model_path = run_dir / "input" / "model_config.json"
    if not model_path.is_file():
        raise RuntimeError(f"model configuration is missing: {model_path}")
    model = read_json(model_path)
    params_scala = run_dir / "generated" / "chisel" / "src" / "main" / "scala" / "spatialaccagent" / "generated" / "GeneratedDesignParams.scala"
    params_text = params_scala.read_text(encoding="utf-8", errors="ignore") if params_scala.exists() else ""
    hidden_match = re.search(r"hiddenSize\s*=\s*(\d+)", params_text)
    lanes_match = re.search(r"lanes\s*=\s*(\d+)", params_text)
    seq_match = re.search(r"targetMaxSeqLen:\s*Int\s*=\s*(\d+)", params_text)
    bindings_path = run_dir / "parameter_binding" / "parameter_binding.json"
    bindings = read_json(bindings_path) if bindings_path.is_file() else {}
    binding_rows = bindings.get("bindings", []) if isinstance(bindings.get("bindings"), list) else []
    first_params = next(
        (row.get("params") for row in binding_rows if isinstance(row, dict) and isinstance(row.get("params"), dict)),
        {},
    )
    hidden_size = int(hidden_match.group(1)) if hidden_match else int(model.get("hidden_size") or 0)
    lanes = int(lanes_match.group(1)) if lanes_match else int(first_params.get("lanes") or 0)
    max_seq_len = int(seq_match.group(1)) if seq_match else int(model.get("target_max_seq_len") or 0)
    if hidden_size <= 0 or lanes <= 0 or max_seq_len <= 0:
        raise RuntimeError(
            "cannot derive hidden_size, lanes, and target_max_seq_len from current generated/model artifacts"
        )
    return {
        "data_w": width_from_decl(text, "io_in_bits_data", 256),
        "addr_w": width_from_decl(text, "io_in_bits_addr", 11),
        "cfg_seq_w": width_from_decl(text, "io_cfg_seqlen", 5),
        "pos_w": width_from_decl(text, "io_position", 4),
        "hidden_size": hidden_size,
        "lanes": lanes,
        "max_seq_len": max_seq_len,
        "stream_beats": max_seq_len * max(1, hidden_size // max(1, lanes)),
    }


def model_layers(run_dir: Path) -> int:
    path = run_dir / "input" / "model_config.json"
    if not path.exists():
        raise RuntimeError(f"model configuration is missing: {path}")
    value = read_json(path).get("num_layers")
    if not isinstance(value, int) or value <= 0:
        raise RuntimeError("model configuration has no positive num_layers")
    return value


def sv_range(width: int) -> str:
    return "" if width == 1 else f"[{width - 1}:0] "


