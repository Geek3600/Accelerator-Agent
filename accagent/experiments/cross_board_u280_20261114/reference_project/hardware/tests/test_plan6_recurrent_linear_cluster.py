import subprocess
import tempfile
import unittest
from datetime import datetime
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
VERILATOR = Path("/usr/bin/verilator")
REPORT_PATH = ROOT / "results/plan6/recurrent_linear_cluster_rtl.txt"


class Plan6RecurrentLinearClusterTests(unittest.TestCase):
    def test_full_huginn_operator_through_shadow_ring_and_three_slrs(self):
        if not VERILATOR.is_file():
            self.fail(f"Verilator is required at {VERILATOR}")

        with tempfile.TemporaryDirectory(prefix="loopquant_plan6_linear_cluster_") as temp_name:
            build_dir = Path(temp_name) / "obj_dir"
            build = subprocess.run(
                [
                    str(VERILATOR), "--binary", "--timing", "-Wno-fatal", "--build-jobs", "4",
                    "-DPLAN6_CLUSTER_TEST", "--top-module", "tb_rtwsr_recurrent_linear_cluster",
                    "--Mdir", str(build_dir),
                    str(ROOT / "hardware/radix3_5trit_decoder.sv"),
                    str(ROOT / "hardware/scale_hoisted_ternary_lane.sv"),
                    str(ROOT / "hardware/usw512_word_decoder.sv"),
                    str(ROOT / "hardware/usw512_dual_track_channel.sv"),
                    str(ROOT / "hardware/usw512_channel_array.sv"),
                    str(ROOT / "hardware/uram_active_pool_bank.sv"),
                    str(ROOT / "hardware/uram_shadow_ring.sv"),
                    str(ROOT / "hardware/rtwsr_streaming_weight_store.sv"),
                    str(ROOT / "hardware/rtwsr_top.sv"),
                    str(ROOT / "hardware/rtwsr_recurrent_linear_cluster.sv"),
                    str(ROOT / "hardware/tests/tb_rtwsr_top.sv"),
                ],
                cwd=temp_name,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                check=False,
            )
            if build.returncode:
                self.fail("Verilator build failed:\n" + "\n".join(build.stdout.splitlines()[-100:]))

            simulation = subprocess.run(
                [str(build_dir / "Vtb_rtwsr_recurrent_linear_cluster")],
                cwd=temp_name,
                text=True,
                stdout=subprocess.PIPE,
                stderr=subprocess.STDOUT,
                check=False,
                timeout=3600,
            )
            if simulation.returncode:
                self.fail("full-size recurrent linear-cluster regression failed:\n" +
                          "\n".join(simulation.stdout.splitlines()[-100:]))
            self.assertIn("5280, K=17920, ROUNDS=32", simulation.stdout)
            self.assertIn("168960 channel-round outputs matched software reference", simulation.stdout)
            self.assertIn("full operator stream drained through the shared shadow ring", simulation.stdout)

            metrics = [
                line for line in simulation.stdout.splitlines()
                if line.startswith("PASS:") or line.startswith("MEASURE:")
            ]
            report = [
                "format: Plan6-Recurrent-Linear-Cluster-RTL-v1",
                f"created: {datetime.now().astimezone().isoformat(timespec='seconds')}",
                "device_target: 3 SLR x 32 INT8 output channels",
                "model_geometry: Huginn-3.5B operator C_OUT=5280 K=17920 windows=70 rounds=32",
                "operator_scope: one full 5280x17920 linear operator through shared shadow ring and three primary pools",
                "weight_source: deterministic synthetic USW-512 records generated by the testbench; not a Plan 4 model payload",
                "activation_source: deterministic INT8 window values generated by the testbench",
                "weight_stream_records: 369600",
                "software_reference_comparisons: 168960 channel-round outputs",
                f"simulator: {subprocess.run([str(VERILATOR), '--version'], check=True, text=True, capture_output=True).stdout.strip()}",
                "build: --binary --timing --build-jobs 4; PLAN6_CLUSTER_TEST",
                *metrics,
            ]
            REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
            REPORT_PATH.write_text("\n".join(report) + "\n")


if __name__ == "__main__":
    unittest.main()
